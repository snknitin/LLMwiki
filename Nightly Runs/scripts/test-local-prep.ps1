# Real desktop-Qwen dispatch/tool-use check through the production -PrepOnly path, on synthetic data.
$ErrorActionPreference = 'Stop'
$root = Join-Path $env:TEMP ("agents-board-local-prep-" + (Get-Date -Format yyyyMMdd-HHmmss))
$vault = Join-Path $root 'vault'; $projects = Join-Path $root 'projects'; $d = Join-Path $projects 'prep-fixture'
New-Item -ItemType Directory -Force (Join-Path $vault 'Nightly Runs\agent-rules'), $d | Out-Null
Set-Content (Join-Path $d 'BUILD_SPEC.md') "# Synthetic prep fixture`nUI: none`nNext target: implement integer addition."
git -C $d init -q -b main
git -C $d config user.name 'Prep fixture'; git -C $d config user.email fixture@localhost
git -C $d add BUILD_SPEC.md; git -C $d commit -qm 'Seed synthetic preparation target'
Set-Content (Join-Path $vault 'Nightly Runs\Project Priorities.md') "## Tonight`n### Hermes`n## Priority order`n1. prep-fixture"
Set-Content (Join-Path $vault 'Nightly Runs\agent-rules\overnight-prompt.md') 'No builder runs in this qualification.'
Set-Content (Join-Path $vault 'Nightly Runs\agent-rules\prep-prompt.md') @"
This is a bounded synthetic prep dispatch qualification, not a portfolio preparation run.
Only touch $d. Read its BUILD_SPEC.md with a tool. Write PREP-RECEIPT.md containing the exact Next target from that file.
Run a terminal command that asserts 2 + 2 == 4. Commit only PREP-RECEIPT.md; there is no remote, so do not push.
The Items below are generated by the production runner; for this qualification perform only the receipt task above,
not the full make-overnight-ready skill. Never read or change another project or the real vault.
Finish with PREP LOCAL OK. Use the pinned local model only.
"@
$oldVault = $env:OVERNIGHT_VAULT; $oldProjects = $env:OVERNIGHT_PROJECTS
try {
    $env:OVERNIGHT_VAULT = $vault; $env:OVERNIGHT_PROJECTS = $projects
    & powershell.exe -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot 'overnight-run.ps1') -PrepOnly -PrepMinutes 3
    if ($LASTEXITCODE) { throw 'Local PrepOnly failed' }
    if ((Get-Content (Join-Path $d 'PREP-RECEIPT.md') -Raw) -notmatch 'implement integer addition') { throw 'Prep did not read and record the target' }
    if ((git -C $d log -1 --format=%s) -eq 'Seed synthetic preparation target') { throw 'Prep did not commit its work' }
    $log = Get-ChildItem $projects -Recurse -Filter '_prep.log' | Select-Object -First 1
    $text = (Get-Content $log.FullName -Raw) -replace "`0", ''
    if ($text -notmatch 'LOCAL ROUTE: qwen3.8-27b-desktop at http://127.0.0.1:11435/v1' -or $text -notmatch 'PREP LOCAL OK') { throw 'Unexpected prep route or no completion marker' }
    if ($text -notmatch 'profiles[\\/]agents-board-prep') { throw 'Prep did not reuse the stable service profile' }
    Write-Output "LOCAL PREP FLOW OK: desktop Qwen read the target, used tools, wrote and committed the receipt. Evidence: $root"
} finally { $env:OVERNIGHT_VAULT = $oldVault; $env:OVERNIGHT_PROJECTS = $oldProjects }
